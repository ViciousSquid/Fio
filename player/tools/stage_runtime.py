"""Prepare an Android-private copy of the current Fio engine.

Desktop engine/editor/plugin sources are inputs only. Small Android adapters
are applied in a separate build directory, never in the project checkout.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

RUNTIME_MODULES = {
    'things': 'entities', 'io_system': 'io_system',
    'io_handlers': 'io_handlers', 'state_values': 'state_values',
    'portal_links': 'portal_links',
}
ENGINE_ADAPTERS = (
    'logic_combat', 'logic_thread', 'logic_session', 'logic_player', 'threaded_game_state',
    'cutscene_runtime', 'glb_loader', 'obj_loader', 'logic_collision', 'terrain',
)


def prepare_runtime(private, project=None):
    project = Path(project or Path(__file__).resolve().parents[2]).resolve()
    private = Path(private).resolve()
    if private == project or project.is_relative_to(private):
        raise ValueError('Android staging must be separate from the project sources')
    private.mkdir(parents=True, exist_ok=True)
    sources = {}

    def copy_source(source, target):
        original = (project / source).resolve()
        destination = (private / target).resolve()
        if not original.is_relative_to(project) or not destination.is_relative_to(private):
            raise ValueError('Runtime staging path escapes its source or destination')
        raw = original.read_bytes()
        sources[source] = hashlib.sha256(raw).hexdigest()
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(raw)

    # Never retain a fallback archive generated by an older staging version.
    (private / 'player/builtin.fiopak').unlink(missing_ok=True)
    # Buildozer lowercases patterns but not filenames in nested directories,
    # so its lowercase exclusion misses the committed uppercase _SHOWCASE.
    # Keep this fixture separate from the installable app on every build.
    (private / 'player/_SHOWCASE.fiopak').unlink(missing_ok=True)

    # Start from the checked-out engine on every build, including repeated hooks.
    for name in ENGINE_ADAPTERS:
        copy_source(f'engine/{name}.py', f'engine/{name}.py')
    for old, new in RUNTIME_MODULES.items():
        copy_source(f'editor/{old}.py', f'engine/{new}.py')

    patch = project / 'player/overlays/android-runtime.patch'
    result = subprocess.run(
        ['patch', '--batch', '--forward', '--fuzz=0', '-p1', '-i', str(patch)],
        cwd=private, capture_output=True, text=True,
    )
    if result.returncode:
        raise RuntimeError('The Android adapter does not match this engine checkout:\n' +
                           (result.stdout + result.stderr)[-6000:])

    editor = private / 'editor'
    editor.mkdir(exist_ok=True)
    (editor / '__init__.py').write_text('"""APK runtime compatibility imports; no desktop UI is shipped."""\n')
    for old, new in RUNTIME_MODULES.items():
        (editor / f'{old}.py').write_text(
            f'import sys\nfrom engine import {new} as _runtime\nsys.modules[__name__] = _runtime\n')
    # Built-in and installed plugins use the same full Thing class on Android.
    (private / 'plugins').mkdir(exist_ok=True)
    (private / 'plugins/entitybase.py').write_text(
        'from engine.entities import Thing\n'
        'def __getattr__(name):\n'
        '    if name == "Prop":\n'
        '        from engine.prop_entity import Prop\n'
        '        return Prop\n'
        '    raise AttributeError(name)\n')
    copy_source('player/android_entrypoint.py', 'main.py')
    # Renderer-owned noise must match desktop without depending on loose assets.
    copy_source('assets/noise_3d.bin', 'player/runtime/noise_3d.bin')
    for source, digest in sources.items():
        if hashlib.sha256((project / source).read_bytes()).hexdigest() != digest:
            raise RuntimeError(f'Project source changed during staging: {source}')
    receipt = {'desktop_sources_unchanged': True, 'source_sha256': sources}
    (private / 'player').mkdir(exist_ok=True)
    (private / 'player/runtime-build.json').write_text(json.dumps(receipt, indent=2) + '\n')
    return receipt


def stage_tree(destination, project=None):
    """Stage the same source tree for isolated host tests, without Buildozer."""
    project = Path(project or Path(__file__).resolve().parents[2]).resolve()
    destination = Path(destination).resolve()
    if destination.exists():
        raise FileExistsError(f'Choose an empty staging destination: {destination}')
    destination.mkdir(parents=True)
    for name in ('engine', 'plugins', 'player', 'maps'):
        shutil.copytree(project / name, destination / name,
                        ignore=shutil.ignore_patterns('.buildozer', 'bin', '__pycache__',
                                                     '*.pyc', '.git', 'p4a-recipes'))
    shutil.copy2(project / 'python_runtime.py', destination / 'python_runtime.py')
    return prepare_runtime(destination, project)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination')
    args = parser.parse_args(argv)
    receipt = stage_tree(args.destination)
    print(f'Staged Android engine; {len(receipt["source_sha256"])} desktop source hashes unchanged.')


if __name__ == '__main__':
    main()
