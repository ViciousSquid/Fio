"""Regenerate the private, 100-unit playerstart sign from the reference artwork.

Y is up; the player's centre is the origin (feet -50, top +50).
The sign faces +Z. This is editor artwork, never a placeable model preset.
"""

import math
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from engine.constants import PLAYER_HULL_SIZE


class Mesh:
    def __init__(self):
        self.vertices = []
        self.faces = {}

    def face(self, points, material):
        indices = []
        for x, y, z in points:
            indices.append(len(self.vertices) + 1)
            self.vertices.append((x, y - 50.0, z))
        self.faces.setdefault(material, []).append(indices)

    def prism(self, outline, front, back, material):
        """Extrude an XY polygon, triangulating its concave front and back."""
        area = sum(a[0]*b[1] - b[0]*a[1]
                   for a, b in zip(outline, outline[1:] + outline[:1]))
        points = list(outline if area > 0 else reversed(outline))
        remaining = list(range(len(points)))

        def cross(a, b, c):
            return (b[0]-a[0])*(c[1]-a[1]) - (b[1]-a[1])*(c[0]-a[0])

        while len(remaining) > 2:
            for j, b in enumerate(remaining):
                a, c = remaining[j-1], remaining[(j+1) % len(remaining)]
                pa, pb, pc = points[a], points[b], points[c]
                if cross(pa, pb, pc) <= 1e-8:
                    continue
                if any(cross(pa, pb, points[k]) >= -1e-8
                       and cross(pb, pc, points[k]) >= -1e-8
                       and cross(pc, pa, points[k]) >= -1e-8
                       for k in remaining if k not in (a, b, c)):
                    continue
                tri = (pa, pb, pc)
                self.face([(x, y, front) for x, y in tri], material)
                self.face([(x, y, back) for x, y in reversed(tri)], material)
                del remaining[j]
                break
            else:
                raise ValueError('Could not triangulate sign outline')
        for a, b in zip(points, points[1:] + points[:1]):
            self.face([(a[0], a[1], back), (b[0], b[1], back),
                       (b[0], b[1], front), (a[0], a[1], front)], material)

    def edge(self, a, b, radius=0.12):
        # Eight-sided edge highlight, including the acrylic's visible thickness.
        import numpy as np
        a, b = np.array(a, float), np.array(b, float)
        axis = b-a
        axis /= np.linalg.norm(axis)
        u = np.cross(axis, (0, 1, 0) if abs(axis[1]) < .9 else (1, 0, 0))
        u /= np.linalg.norm(u)
        v = np.cross(axis, u)
        ring = [radius*(u*math.cos(i*math.tau/8) + v*math.sin(i*math.tau/8))
                for i in range(8)]
        for i in range(8):
            j = (i+1) % 8
            self.face([a+ring[i], b+ring[i], b+ring[j], a+ring[j]], 'edge')

    def write(self, path):
        lines = ['# Fio private playerstart artwork; generated by tools/build_playerstart_model.py',
                 '# up_axis: Y', '# 100 units high, centred on the player hull',
                 'mtllib playerstart.mtl']
        # Fit the reference artwork to the exact standing player's dimensions.
        extents = [max(v[i] for v in self.vertices) - min(v[i] for v in self.vertices)
                   for i in range(3)]
        scales = [size / extent for size, extent in zip(PLAYER_HULL_SIZE, extents)]
        lines += ['v %.6f %.6f %.6f' % tuple(v*k for v, k in zip(point, scales))
                  for point in self.vertices]
        for material, faces in self.faces.items():
            lines.append('usemtl ' + material)
            lines += ['f ' + ' '.join(map(str, face)) for face in faces]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def build():
    mesh = Mesh()
    # Head and continuous rounded body, arms and separated legs: actual mesh,
    # with the same print visible from either side of the clear sign.
    head = [(7.1*math.cos(i*math.tau/48), 89+8*math.sin(i*math.tau/48))
            for i in range(48)]
    mesh.prism(head, .40, -.40, 'ink')
    body = [(-6.5, 79)]

    def line(x, y):
        body.append((x, y))

    def curve(cx1, cy1, cx2, cy2, x, y):
        x0, y0 = body[-1]
        for i in range(1, 13):
            t = i/12
            s = 1-t
            body.append((s**3*x0 + 3*s*s*t*cx1 + 3*s*t*t*cx2 + t**3*x,
                         s**3*y0 + 3*s*s*t*cy1 + 3*s*t*t*cy2 + t**3*y))

    curve(-12, 79, -17, 73, -17, 67)
    line(-17, 49)
    curve(-17, 43, -11, 43, -11, 49)
    line(-11, 67)
    line(-9.5, 67)
    line(-9.5, 21)
    curve(-9.5, 15, -1, 15, -1, 21)
    line(-1, 46)
    line(1, 46)
    line(1, 21)
    curve(1, 15, 9.5, 15, 9.5, 21)
    line(9.5, 67)
    line(11, 67)
    line(11, 49)
    curve(11, 43, 17, 43, 17, 49)
    line(17, 67)
    curve(17, 73, 12, 79, 6.5, 79)
    mesh.prism(body, .40, -.40, 'ink')

    # Clear rectangular upright and a folded acrylic foot with triangular ends.
    # Edge centrelines stay inside the 100-unit overall bounds.
    panel = [(-27, 10), (27, 10), (27, 100), (-27, 100)]
    mesh.prism(panel, .275, -.275, 'acrylic')
    for a, b in zip(panel, panel[1:] + panel[:1]):
        mesh.edge((a[0], min(a[1], 99.88), 0),
                  (b[0], min(b[1], 99.88), 0))
    for sign in (-1, 1):
        mesh.face([(-32, .12, sign*14), (32, .12, sign*14),
                   (27, 17, 0), (-27, 17, 0)], 'acrylic')
        for x in (-27, 27):
            mesh.edge((x, .12, sign*14), (x, 17, 0))
        mesh.edge((-32, .12, sign*14), (32, .12, sign*14))
    mesh.face([(-32.12, .12, -14.12), (32.12, .12, -14.12),
               (32.12, .12, 14.12), (-32.12, .12, 14.12)], 'acrylic')
    for x in (-32, 32):
        mesh.edge((x, .12, -14), (x, .12, 14))
    for x in (-27, 27):
        mesh.face([(x, .12, -14), (x, .12, 14), (x, 17, 0)], 'acrylic')
    mesh.write(ROOT / 'assets/editor/playerstart.obj')


if __name__ == '__main__':
    build()
